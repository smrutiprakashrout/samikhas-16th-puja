// GENERATED helper for the video project. Copies website assets into public/ and generated source.
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const generatedHeader = '// GENERATED by scripts/sync-assets.mjs. DO NOT EDIT.\n';

function exists(p) {
  return fs.existsSync(p);
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function group(label, fn) {
  try {
    const count = fn();
    console.log(`${label}: ${count} file(s)`);
  } catch (err) {
    console.warn(`${label}: WARNING ${err.message}`);
  }
}

function copyDir(srcRel, destRel, { onlySvg = false, skipUnderscore = false } = {}) {
  const src = path.join(root, srcRel);
  const dest = path.join(root, destRel);
  if (!exists(src)) throw new Error(`missing source ${srcRel}`);
  ensureDir(dest);
  let count = 0;
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const name = entry.name;
    if (onlySvg && path.extname(name).toLowerCase() !== '.svg') continue;
    if (skipUnderscore && name.startsWith('_')) continue;
    fs.copyFileSync(path.join(src, name), path.join(dest, name));
    count++;
  }
  return count;
}

function copyFile(srcRel, destRel, { required = false } = {}) {
  const src = path.join(root, srcRel);
  const dest = path.join(root, destRel);
  if (!exists(src)) {
    if (required) throw new Error(`missing required source ${srcRel}`);
    throw new Error(`missing source ${srcRel}`);
  }
  ensureDir(path.dirname(dest));
  fs.copyFileSync(src, dest);
  return 1;
}

group('img', () => copyDir('../assets/img', 'public/img'));
group('svg', () => copyDir('../assets/svg', 'public/svg', { onlySvg: true, skipUnderscore: true }));
group('audio', () => copyFile('../assets/audio/bgm.mp3', 'public/audio/bgm.mp3'));
group('gate door', () => copyFile('../src/sections/00-gate/door.svg', 'public/svg/door.svg'));
group('assets-src', () => copyDir('assets-src', 'public/svg', { onlySvg: true }));

function copyGenerated(srcRel, base) {
  const src = path.join(root, srcRel);
  const destDir = path.join(root, 'src/generated');
  ensureDir(destDir);
  if (!exists(src)) throw new Error(`missing required source ${srcRel}`);
  const body = fs.readFileSync(src, 'utf8');
  fs.writeFileSync(path.join(destDir, `${base}.js`), generatedHeader + body);
  return 1;
}

try {
  copyGenerated('../src/content.js', 'content');
  console.log('content.js: 1 file(s)');
} catch (err) {
  console.error(`content.js: ERROR ${err.message}`);
  process.exitCode = 1;
}

group('garland.js', () => copyGenerated('../src/core/garland.js', 'garland'));

const declDir = path.join(root, 'src/generated');
ensureDir(declDir);
fs.writeFileSync(path.join(declDir, 'content.d.ts'), 'export const content: any;\n');
fs.writeFileSync(path.join(declDir, 'garland.d.ts'), 'export function createGarland(seed?: number): any;\n');
console.log('type declarations: 2 file(s)');
